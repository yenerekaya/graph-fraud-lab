const assert=require('node:assert/strict');
const {filterTransactions,traceRoute,toCSV}=require('../src/graph_fraud_lab/dashboard-core.js');
const row=(id,source,target,amount,minute)=>({id,source,target,amount,timestamp:new Date(Date.UTC(2026,0,1,0,minute)).toISOString()});
const rows=[row('0','a','b',100,1),row('1','b','c',90,0),row('2','b','c',80,2),row('3','a','c',500,10)];
assert.deepEqual(traceRoute(rows,['a','b','c'],'a','c').map(r=>r.id),['0','2']);
assert.deepEqual(traceRoute(rows,['a','b','c'],'a','c',1).map(r=>r.id),['3']);
assert.deepEqual(traceRoute(rows,['a','b','c'],'c','a'),[]);
assert.deepEqual(traceRoute([row('0','a','b',100,1),row('1','b','c',100,1)],['a','b','c'],'a','c'),[]);
assert.throws(()=>traceRoute(rows,['a','b','c'],'a','a'));
assert.throws(()=>traceRoute(rows,['a','b','c'],'a','c',0));
assert.throws(()=>traceRoute(rows,['a','b','c'],'a','missing'));
assert.deepEqual(filterTransactions(rows,{query:' B ',start:'2026-01-01T00:01:00Z',end:'2026-01-01T00:02:00Z'}).map(r=>r.id),['0']);
assert.deepEqual(filterTransactions(rows,{minAmount:500}).map(r=>r.id),['3']);
assert.deepEqual(filterTransactions(rows,{query:'missing'}),[]);
assert.throws(()=>filterTransactions(rows,{start:'invalid'}));
assert.throws(()=>filterTransactions(rows,{minAmount:-1}));
assert.throws(()=>filterTransactions(rows,{start:'2026-01-02',end:'2026-01-01'}));
const csv=toCSV([row('=1+1','a,"quoted"','b',100,1)]);
assert.ok(csv.includes('"\'=1+1"'));
assert.ok(csv.includes('"a,""quoted"""'));
assert.equal(csv.split('\r\n').length,2);
assert.equal(toCSV([]),'id,source,target,amount,timestamp');
console.log('Dashboard core: 17 assertions passed');
